// Health Check Monitor dashboard — talks directly to the GitHub REST API.
// Read-only without a token; add a fine-grained PAT (Contents + Actions +
// Secrets: read & write) to edit services.yml, trigger runs, and manage secrets.

const OWNER = "vijevira";
const REPO = "cron-jobs";
const BRANCH = "main";
const SERVICES_PATH = "services.yml";
const STATE_PATH = "state.json";
const WORKFLOW_FILE = "cron-jobs.yml";
const API = "https://api.github.com";

const SERVICES_HEADER = `# List every service you want monitored here.
# - name: short label used in logs, state.json, and alert emails
# - url: the health-check endpoint to call
# - method: HTTP method, defaults to GET (set POST for check-endpoints that require it)
# - expected_status: HTTP status code(s) that count as "healthy". Can be a
#     single code (e.g. 200), a list (e.g. [200, 202, 204]), or omitted
#     entirely to accept any 2xx response as success.
# - timeout: seconds to wait before treating the request as failed (default 10)
# - headers: optional dict of request headers
# - body: optional dict, sent as JSON (only meaningful for POST/PUT/etc)
# - auth: optional basic-auth block: { type: basic, username: ..., password: ... }
#
# NEVER put real credentials directly in this file — it's committed to git.
# Instead reference an env var with \${VAR_NAME}, add the real value as a repo
# secret (use the "Repo secrets" panel in this dashboard), and it will be
# wired into the workflow's env block automatically.
#
# NOTE: this file is regenerated by the dashboard on every save — hand-added
# comments below this header will not survive an edit made through the UI.

`;

let servicesDoc = null; // { services: [...] }
let servicesSha = null;
let stateDoc = {};

// ---------- storage ----------

function getToken() {
  try { return localStorage.getItem("gh_pat") || ""; } catch { return ""; }
}
function setToken(t) {
  try {
    if (t) localStorage.setItem("gh_pat", t);
    else localStorage.removeItem("gh_pat");
  } catch {}
}

// ---------- utf8-safe base64 ----------

function b64EncodeUtf8(str) {
  const bytes = new TextEncoder().encode(str);
  let binary = "";
  bytes.forEach((b) => (binary += String.fromCharCode(b)));
  return btoa(binary);
}
function b64DecodeUtf8(b64) {
  const binary = atob(b64.replace(/\n/g, ""));
  const bytes = Uint8Array.from(binary, (c) => c.charCodeAt(0));
  return new TextDecoder().decode(bytes);
}

// ---------- toast ----------

let toastTimer = null;
function toast(msg, isError) {
  const el = document.getElementById("toast");
  el.textContent = msg;
  el.style.background = isError ? "#7f1d1d" : "#1a1d23";
  el.classList.remove("hidden");
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => el.classList.add("hidden"), 4000);
}

// ---------- GitHub API ----------

async function gh(path, opts = {}) {
  const token = getToken();
  const headers = Object.assign(
    { Accept: "application/vnd.github+json" },
    opts.headers || {}
  );
  if (token) headers.Authorization = `Bearer ${token}`;
  const resp = await fetch(`${API}${path}`, Object.assign({}, opts, { headers }));
  if (!resp.ok) {
    let detail = "";
    try {
      detail = (await resp.json()).message || "";
    } catch {}
    throw new Error(`GitHub API ${resp.status} ${path}${detail ? ": " + detail : ""}`);
  }
  if (resp.status === 204) return null;
  return resp.json();
}

async function getFile(path) {
  const data = await gh(`/repos/${OWNER}/${REPO}/contents/${path}?ref=${BRANCH}`);
  return { content: b64DecodeUtf8(data.content), sha: data.sha };
}

async function putFile(path, content, sha, message) {
  return gh(`/repos/${OWNER}/${REPO}/contents/${path}`, {
    method: "PUT",
    body: JSON.stringify({
      message,
      content: b64EncodeUtf8(content),
      sha,
      branch: BRANCH,
    }),
  });
}

async function listRuns() {
  const data = await gh(
    `/repos/${OWNER}/${REPO}/actions/workflows/${WORKFLOW_FILE}/runs?per_page=15`
  );
  return data.workflow_runs || [];
}

async function dispatchRun() {
  await gh(`/repos/${OWNER}/${REPO}/actions/workflows/${WORKFLOW_FILE}/dispatches`, {
    method: "POST",
    body: JSON.stringify({ ref: BRANCH }),
  });
}

async function listSecrets() {
  const data = await gh(`/repos/${OWNER}/${REPO}/actions/secrets`);
  return data.secrets || [];
}

async function deleteSecret(name) {
  await gh(`/repos/${OWNER}/${REPO}/actions/secrets/${encodeURIComponent(name)}`, {
    method: "DELETE",
  });
}

async function setSecret(name, value) {
  await sodium.ready;
  const keyData = await gh(`/repos/${OWNER}/${REPO}/actions/secrets/public-key`);
  const pubKey = sodium.from_base64(keyData.key, sodium.base64_variants.ORIGINAL);
  const messageBytes = new TextEncoder().encode(value);
  const sealed = sodium.crypto_box_seal(messageBytes, pubKey);
  const encryptedValue = sodium.to_base64(sealed, sodium.base64_variants.ORIGINAL);
  await gh(`/repos/${OWNER}/${REPO}/actions/secrets/${encodeURIComponent(name)}`, {
    method: "PUT",
    body: JSON.stringify({ encrypted_value: encryptedValue, key_id: keyData.key_id }),
  });
}

async function ensureWorkflowEnvLine(secretName) {
  const { content, sha } = await getFile(`.github/workflows/${WORKFLOW_FILE}`);
  const line = `${secretName}: \${{ secrets.${secretName} }}`;
  const alreadyWired = content.split("\n").some((l) => l.trim() === line);
  if (alreadyWired) return;
  const anchor = "# Add one line per ${VAR_NAME} placeholder used in services.yml,";
  const idx = content.indexOf(anchor);
  if (idx === -1) {
    toast(
      `Secret saved, but couldn't find the anchor comment in ${WORKFLOW_FILE} — add "${line}" to its env block manually.`,
      true
    );
    return;
  }
  const lineStart = content.lastIndexOf("\n", idx) + 1;
  const indent = content.slice(lineStart, idx).match(/^\s*/)[0];
  const updated =
    content.slice(0, lineStart) + `${indent}${line}\n` + content.slice(lineStart);
  await putFile(
    `.github/workflows/${WORKFLOW_FILE}`,
    updated,
    sha,
    `chore: wire ${secretName} into workflow env`
  );
}

// ---------- data loading ----------

async function loadState() {
  try {
    const { content } = await getFile(STATE_PATH);
    stateDoc = JSON.parse(content || "{}");
  } catch (e) {
    stateDoc = {};
  }
}

async function loadServices() {
  const { content, sha } = await getFile(SERVICES_PATH);
  servicesSha = sha;
  servicesDoc = jsyaml.load(content) || { services: [] };
  if (!Array.isArray(servicesDoc.services)) servicesDoc.services = [];
}

async function saveServices(message) {
  const body = jsyaml.dump(servicesDoc, { lineWidth: -1, noRefs: true });
  const { sha } = await getFile(SERVICES_PATH); // re-fetch sha in case it moved
  await putFile(SERVICES_PATH, SERVICES_HEADER + body, sha, message);
  await loadServices();
}

// ---------- rendering ----------

function renderStatus() {
  const grid = document.getElementById("statusGrid");
  grid.innerHTML = "";
  const names = (servicesDoc?.services || []).map((s) => s.name);
  const allNames = new Set([...names, ...Object.keys(stateDoc)]);
  if (allNames.size === 0) {
    grid.innerHTML = `<div class="muted">No services configured yet.</div>`;
    return;
  }
  allNames.forEach((name) => {
    const entry = stateDoc[name];
    const status = entry?.status || "unknown";
    const div = document.createElement("div");
    div.className = `card status-card ${status}`;
    div.innerHTML = `
      <div class="status-name">${escapeHtml(name)}</div>
      <span class="status-badge ${status}">${status}</span>
      <div class="status-detail">${escapeHtml(entry?.detail || "no data yet")}</div>
      <div class="status-detail">${entry?.last_checked ? "checked " + timeAgo(entry.last_checked) : ""}</div>
    `;
    grid.appendChild(div);
  });
}

function renderRuns(runs) {
  const body = document.getElementById("runsBody");
  body.innerHTML = "";
  if (!runs.length) {
    body.innerHTML = `<tr><td colspan="5" class="muted">No runs yet — trigger one with "Run now".</td></tr>`;
    return;
  }
  runs.forEach((run) => {
    const pillClass =
      run.status !== "completed" ? "other" : run.conclusion === "success" ? "success" : "failure";
    const label = run.status !== "completed" ? run.status : run.conclusion;
    const started = new Date(run.run_started_at || run.created_at);
    const finished = run.updated_at ? new Date(run.updated_at) : null;
    const duration =
      run.status === "completed" && finished
        ? `${Math.max(1, Math.round((finished - started) / 1000))}s`
        : "—";
    const tr = document.createElement("tr");
    tr.innerHTML = `
      <td><span class="pill ${pillClass}">${label}</span></td>
      <td>${timeAgo(started.toISOString())}</td>
      <td>${duration}</td>
      <td>${escapeHtml(run.event)}</td>
      <td><a class="link" href="${run.html_url}" target="_blank" rel="noopener">view</a></td>
    `;
    body.appendChild(tr);
  });
}

function renderServices() {
  const body = document.getElementById("servicesBody");
  body.innerHTML = "";
  const services = servicesDoc?.services || [];
  if (!services.length) {
    body.innerHTML = `<tr><td colspan="6" class="muted">No services yet.</td></tr>`;
    return;
  }
  services.forEach((s, idx) => {
    const expected = Array.isArray(s.expected_status)
      ? s.expected_status.join(", ")
      : s.expected_status ?? "any 2xx";
    const tr = document.createElement("tr");
    tr.innerHTML = `
      <td>${escapeHtml(s.name)}</td>
      <td>${escapeHtml(s.method || "GET")}</td>
      <td style="max-width:280px;overflow:hidden;text-overflow:ellipsis;white-space:nowrap">${escapeHtml(s.url)}</td>
      <td>${escapeHtml(String(expected))}</td>
      <td>${s.timeout ?? 10}s</td>
      <td class="row">
        <button class="btn secondary small" data-edit="${idx}">Edit</button>
        <button class="btn danger small" data-delete="${idx}">Delete</button>
      </td>
    `;
    body.appendChild(tr);
  });
  body.querySelectorAll("[data-edit]").forEach((btn) =>
    btn.addEventListener("click", () => openServiceModal(Number(btn.dataset.edit)))
  );
  body.querySelectorAll("[data-delete]").forEach((btn) =>
    btn.addEventListener("click", () => deleteServiceAt(Number(btn.dataset.delete)))
  );
}

function renderSecrets(secrets) {
  const body = document.getElementById("secretsBody");
  body.innerHTML = "";
  if (!secrets.length) {
    body.innerHTML = `<tr><td colspan="3" class="muted">No secrets found (or token lacks Secrets: read).</td></tr>`;
    return;
  }
  secrets.forEach((s) => {
    const tr = document.createElement("tr");
    tr.innerHTML = `
      <td>${escapeHtml(s.name)}</td>
      <td>${timeAgo(s.updated_at)}</td>
      <td><button class="btn danger small" data-del-secret="${escapeHtml(s.name)}">Delete</button></td>
    `;
    body.appendChild(tr);
  });
  body.querySelectorAll("[data-del-secret]").forEach((btn) =>
    btn.addEventListener("click", async () => {
      if (!confirm(`Delete secret "${btn.dataset.delSecret}"? This cannot be undone.`)) return;
      try {
        await deleteSecret(btn.dataset.delSecret);
        toast("Secret deleted.");
        refreshSecrets();
      } catch (e) {
        toast(e.message, true);
      }
    })
  );
}

function escapeHtml(str) {
  return String(str ?? "").replace(/[&<>"']/g, (c) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  }[c]));
}
function timeAgo(iso) {
  if (!iso) return "";
  const diff = (Date.now() - new Date(iso).getTime()) / 1000;
  if (diff < 60) return "just now";
  if (diff < 3600) return `${Math.floor(diff / 60)}m ago`;
  if (diff < 86400) return `${Math.floor(diff / 3600)}h ago`;
  return `${Math.floor(diff / 86400)}d ago`;
}

// ---------- modals ----------

function closeModal() {
  document.getElementById("modalRoot").innerHTML = "";
}

function openServiceModal(index) {
  const editing = index !== undefined && index !== null;
  const s = editing ? servicesDoc.services[index] : {};
  const headerRows = Object.entries(s.headers || {});
  const auth = s.auth || {};

  const root = document.getElementById("modalRoot");
  root.innerHTML = `
    <div class="modal-backdrop">
      <div class="modal">
        <h3>${editing ? "Edit" : "Add"} service</h3>
        <label>Name</label>
        <input type="text" id="f_name" value="${escapeHtml(s.name || "")}" />
        <label>URL</label>
        <input type="text" id="f_url" value="${escapeHtml(s.url || "")}" />
        <label>Method</label>
        <select id="f_method">
          ${["GET", "POST", "PUT", "DELETE"].map(
            (m) => `<option ${((s.method || "GET").toUpperCase() === m) ? "selected" : ""}>${m}</option>`
          ).join("")}
        </select>
        <label>Expected status (blank = any 2xx, or "200" or "200,202,204")</label>
        <input type="text" id="f_expected" value="${
          Array.isArray(s.expected_status) ? s.expected_status.join(",") : s.expected_status ?? ""
        }" />
        <label>Timeout (seconds)</label>
        <input type="number" id="f_timeout" value="${s.timeout ?? 10}" />
        <label>Headers (values may reference \${SECRET_NAME})</label>
        <div id="headerRows"></div>
        <button class="btn secondary small" id="addHeaderRow" type="button">+ header</button>
        <label>Body (JSON, only used for POST/PUT — leave blank for none)</label>
        <textarea id="f_body" rows="3">${s.body ? escapeHtml(JSON.stringify(s.body, null, 2)) : ""}</textarea>
        <label>Basic auth (leave both blank for none; values may reference \${SECRET_NAME})</label>
        <input type="text" id="f_authuser" placeholder="username" value="${escapeHtml(auth.username || "")}" />
        <input type="text" id="f_authpass" placeholder="password" style="margin-top:6px" value="${escapeHtml(auth.password || "")}" />
        <div class="row" style="margin-top:16px; justify-content:flex-end">
          <button class="btn secondary" id="cancelModal">Cancel</button>
          <button class="btn" id="saveModal">Save</button>
        </div>
      </div>
    </div>
  `;

  const headerRowsEl = document.getElementById("headerRows");
  function addHeaderRow(key = "", val = "") {
    const row = document.createElement("div");
    row.className = "kv-row";
    row.innerHTML = `
      <input type="text" placeholder="Header-Name" value="${escapeHtml(key)}" class="hkey" />
      <input type="text" placeholder="value" value="${escapeHtml(val)}" class="hval" />
      <button class="btn danger small" type="button">x</button>
    `;
    row.querySelector("button").addEventListener("click", () => row.remove());
    headerRowsEl.appendChild(row);
  }
  headerRows.forEach(([k, v]) => addHeaderRow(k, v));
  document.getElementById("addHeaderRow").addEventListener("click", () => addHeaderRow());

  document.getElementById("cancelModal").addEventListener("click", closeModal);
  document.getElementById("saveModal").addEventListener("click", async () => {
    const name = document.getElementById("f_name").value.trim();
    const url = document.getElementById("f_url").value.trim();
    if (!name || !url) return toast("Name and URL are required.", true);

    const newService = { name, url };
    const method = document.getElementById("f_method").value;
    if (method !== "GET") newService.method = method;

    const expectedRaw = document.getElementById("f_expected").value.trim();
    if (expectedRaw) {
      const parts = expectedRaw.split(",").map((p) => parseInt(p.trim(), 10)).filter((n) => !isNaN(n));
      newService.expected_status = parts.length > 1 ? parts : parts[0];
    }

    const timeout = parseInt(document.getElementById("f_timeout").value, 10);
    if (!isNaN(timeout) && timeout !== 10) newService.timeout = timeout;

    const headers = {};
    headerRowsEl.querySelectorAll(".kv-row").forEach((row) => {
      const k = row.querySelector(".hkey").value.trim();
      const v = row.querySelector(".hval").value.trim();
      if (k) headers[k] = v;
    });
    if (Object.keys(headers).length) newService.headers = headers;

    const bodyRaw = document.getElementById("f_body").value.trim();
    if (bodyRaw) {
      try {
        newService.body = JSON.parse(bodyRaw);
      } catch {
        return toast("Body must be valid JSON.", true);
      }
    }

    const authUser = document.getElementById("f_authuser").value.trim();
    const authPass = document.getElementById("f_authpass").value.trim();
    if (authUser || authPass) {
      newService.auth = { type: "basic", username: authUser, password: authPass };
    }

    if (editing) servicesDoc.services[index] = newService;
    else servicesDoc.services.push(newService);

    try {
      await saveServices(`${editing ? "Update" : "Add"} service: ${name}`);
      toast("Saved.");
      closeModal();
      renderServices();
      renderStatus();
    } catch (e) {
      toast(e.message, true);
    }
  });
}

async function deleteServiceAt(index) {
  const s = servicesDoc.services[index];
  if (!confirm(`Delete service "${s.name}"?`)) return;
  servicesDoc.services.splice(index, 1);
  try {
    await saveServices(`Remove service: ${s.name}`);
    toast("Deleted.");
    renderServices();
    renderStatus();
  } catch (e) {
    toast(e.message, true);
  }
}

function openSecretModal() {
  const root = document.getElementById("modalRoot");
  root.innerHTML = `
    <div class="modal-backdrop">
      <div class="modal">
        <h3>Add / update secret</h3>
        <label>Name (e.g. INTERNAL_API_TOKEN)</label>
        <input type="text" id="s_name" />
        <label>Value</label>
        <input type="password" id="s_value" />
        <div class="row" style="margin-top:16px; justify-content:flex-end">
          <button class="btn secondary" id="cancelSecretModal">Cancel</button>
          <button class="btn" id="saveSecretModal">Save</button>
        </div>
      </div>
    </div>
  `;
  document.getElementById("cancelSecretModal").addEventListener("click", closeModal);
  document.getElementById("saveSecretModal").addEventListener("click", async () => {
    const name = document.getElementById("s_name").value.trim().toUpperCase().replace(/[^A-Z0-9_]/g, "_");
    const value = document.getElementById("s_value").value;
    if (!name || !value) return toast("Name and value are required.", true);
    try {
      await setSecret(name, value);
      await ensureWorkflowEnvLine(name);
      toast(`Secret ${name} saved and wired into the workflow.`);
      closeModal();
      refreshSecrets();
    } catch (e) {
      toast(e.message, true);
    }
  });
}

// ---------- refresh helpers ----------

async function refreshStatus() {
  await Promise.all([loadState(), loadServices()]);
  renderStatus();
  renderServices();
}

async function refreshRuns() {
  try {
    renderRuns(await listRuns());
  } catch (e) {
    toast(e.message, true);
  }
}

async function refreshSecrets() {
  if (!getToken()) {
    renderSecrets([]);
    return;
  }
  try {
    renderSecrets(await listSecrets());
  } catch (e) {
    renderSecrets([]);
  }
}

function updateTokenStatus() {
  const el = document.getElementById("tokenStatus");
  el.textContent = getToken() ? " Token set — edit mode enabled." : " No token — read-only mode.";
}

